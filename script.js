// PROCESS
const processSteps =
  [...document.querySelectorAll('.process-step')];

let processTimer = null;


const cycleProcess = () => {

  if (processTimer) {
    clearInterval(processTimer);
  }

  let index = 0;


  const activate = () => {

    processSteps.forEach(
      (step, i) => {

        step.classList.toggle(
          'active',
          i === index
        );

      }
    );

    index =
      (index + 1) %
      processSteps.length;

  };


  activate();


  processTimer =
    setInterval(
      activate,
      1200
    );

};


const process =
  document.getElementById('process');


if (
  process &&
  processSteps.length
) {

  const observer =
    new IntersectionObserver(
      entries => {

        entries.forEach(entry => {

          if (entry.isIntersecting) {

            cycleProcess();

          } else if (processTimer) {

            clearInterval(
              processTimer
            );

            processTimer = null;

          }

        });

      },
      {
        threshold: .35
      }
    );


  observer.observe(process);

}


// IMPACT COUNTERS
const impactValues =
  [
    ...document.querySelectorAll('.impact-value')
  ];


const animateCounter = el => {

  if (
    el.dataset.done === 'true'
  ) {
    return;
  }


  const target =
    Number(
      el.dataset.count || 0
    );

  const suffix =
    el.dataset.suffix || '';


  const start =
    performance.now();

  const duration =
    1500;


  el.classList.add(
    'is-counting'
  );


  const tick = now => {

    const progress =
      Math.min(
        (now - start) / duration,
        1
      );

    const eased =
      1 -
      Math.pow(
        1 - progress,
        3
      );


    const value =
      Math.round(
        target * eased
      );


    el.textContent =
      `${value}${suffix}`;


    if (progress < 1) {

      requestAnimationFrame(
        tick
      );

    } else {

      el.textContent =
        `${target}${suffix}`;

      el.dataset.done =
        'true';

    }

  };


  requestAnimationFrame(
    tick
  );

};


const impact =
  document.getElementById(
    'impact'
  );


if (
  impact &&
  impactValues.length
) {

  const impactObserver =
    new IntersectionObserver(
      entries => {

        entries.forEach(
          entry => {

            if (
              entry.isIntersecting
            ) {

              impactValues.forEach(
                (el, index) => {

                  setTimeout(
                    () =>
                      animateCounter(el),
                    index * 120
                  );

                }
              );

              impactObserver.disconnect();

            }

          }
        );

      },
      {
        threshold: .28
      }
    );


  impactObserver.observe(
    impact
  );

}


