// REVIEW DRAG
const reviewTrack =
  document.querySelector(
    '.reviews-track'
  );


if (reviewTrack) {

  let dragging = false;

  let startX = 0;

  let startScroll = 0;

  let moved = false;


  reviewTrack.addEventListener(
    'pointerdown',
    e => {

      if (
        e.pointerType === 'mouse' &&
        e.button !== 0
      ) {
        return;
      }


      dragging = true;

      moved = false;

      startX =
        e.clientX;

      startScroll =
        reviewTrack.scrollLeft;


      reviewTrack.classList.add(
        'is-dragging'
      );


      reviewTrack.setPointerCapture?.(
        e.pointerId
      );

    }
  );


  reviewTrack.addEventListener(
    'pointermove',
    e => {

      if (!dragging) {
        return;
      }


      const delta =
        e.clientX - startX;


      if (
        Math.abs(delta) > 4
      ) {
        moved = true;
      }


      reviewTrack.scrollLeft =
        startScroll -
        delta * 1.25;

    }
  );


  const endDrag = e => {

    if (!dragging) {
      return;
    }


    dragging = false;


    reviewTrack.classList.remove(
      'is-dragging'
    );


    try {

      reviewTrack.releasePointerCapture?.(
        e.pointerId
      );

    } catch {}

  };


  reviewTrack.addEventListener(
    'pointerup',
    endDrag
  );


  reviewTrack.addEventListener(
    'pointercancel',
    endDrag
  );


  reviewTrack.addEventListener(
    'pointerleave',
    e => {

      if (
        e.pointerType === 'mouse' &&
        dragging
      ) {

        endDrag(e);

      }

    }
  );


  reviewTrack.addEventListener(
    'click',
    e => {

      if (moved) {

        e.preventDefault();

        e.stopPropagation();

        moved = false;

      }

    },
    true
  );

}


// REVIEW AUTOPLAY
if (reviewTrack) {

  let autoReviewTimer;


  const stepReviews = () => {

    const card =
      reviewTrack.querySelector(
        '.review-card'
      );

    if (!card) {
      return;
    }


    const styles =
      getComputedStyle(
        reviewTrack
      );


    const gap =
      parseFloat(
        styles.columnGap ||
        styles.gap ||
        '10'
      ) || 10;


    const distance =
      card.getBoundingClientRect().width +
      gap;


    const max =
      Math.max(
        0,
        reviewTrack.scrollWidth -
        reviewTrack.clientWidth
      );


    const next =
      reviewTrack.scrollLeft +
      distance;


    reviewTrack.scrollTo({
      left:
        next >= max - 4
          ? 0
          : next,

      behavior:
        'smooth'
    });

  };


  const startAuto = () => {

    clearInterval(
      autoReviewTimer
    );


    autoReviewTimer =
      setInterval(
        () => {

          if (
            !reviewTrack.classList.contains(
              'is-dragging'
            )
          ) {

            stepReviews();

          }

        },
        4200
      );

  };


  startAuto();


  reviewTrack.addEventListener(
    'pointerdown',
    () =>
      clearInterval(
        autoReviewTimer
      )
  );


  reviewTrack.addEventListener(
    'pointerup',
    startAuto
  );


  reviewTrack.addEventListener(
    'pointercancel',
    startAuto
  );


  document.addEventListener(
    'visibilitychange',
    () => {

      if (
        document.hidden
      ) {

        clearInterval(
          autoReviewTimer
        );

      } else {

        startAuto();

      }

    }
  );

}